import React from "react";
import { cn } from "@/lib/utils";

export interface CardProps extends React.HTMLAttributes<HTMLDivElement> {
  hoverEffect?: boolean;
}

export const Card = React.forwardRef<HTMLDivElement, CardProps>(
  ({ className, hoverEffect = false, children, ...props }, ref) => {
    return (
      <div
        ref={ref}
        className={cn(
          "bg-brand-surface border border-brand-border rounded-2xl overflow-hidden transition-all duration-200",
          hoverEffect &&
            "hover:border-brand-muted/40 hover:bg-brand-elevated/70 hover:shadow-xl hover:shadow-black/40 hover:-translate-y-0.5",
          className
        )}
        {...props}
      >
        {children}
      </div>
    );
  }
);
Card.displayName = "Card";
